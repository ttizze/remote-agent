use super::*;
use agent_protocol::orchestration::{
    Actor, CreationSource, TurnItemBody, projection::ThreadHistoryPage,
};

#[derive(serde::Deserialize)]
struct Page {
    rows: Vec<String>,
    more: bool,
    cursor: String,
}

#[derive(serde::Deserialize)]
struct Trace {
    pages: Vec<Page>,
    committed: usize,
    decision: String,
}

fn body(kind: &str, id: &str) -> TurnItemBody {
    match kind {
        "work" => TurnItemBody::Reasoning {
            text: id.into(),
            streaming: false,
        },
        "notification" => TurnItemBody::Notification {
            source: serde_json::json!({"kind":"delegated_task","taskIds":[]}),
            outcome: "completed".into(),
            summary: id.into(),
            detail: None,
        },
        _ => TurnItemBody::UserMessage {
            created_by: if kind == "agent" {
                Actor::Agent
            } else {
                Actor::User
            },
            input_intent: match kind {
                "user" | "agent" => "turn_start",
                "queued" => "queued_turn",
                "steer" => "steer",
                "promoted" => "promoted_queued_to_steer",
                _ => panic!("unexpected Lean entry: {kind}"),
            }
            .into(),
            message_id: id.into(),
            creation_source: CreationSource::Mobile,
            text: id.into(),
            attachments: vec![],
            scheduled_task_id: None,
            context: None,
        },
    }
}

impl Trace {
    fn check(self) {
        let id = SessionRef::new(None, "history".into()).unwrap();
        let mut snapshot = Snapshot::default();
        open_thread(&mut snapshot, "", serde_json::from_value(serde_json::json!({
            "id":id,"historyCursor":"0","historyHasMore":true,
            "turns":[{"id":"tail","status":"completed","items":[{
                "id":"tail","body":{"inline":{"body":{"assistantText":{"text":"tail","phase":"final"}}}}
            }]}]
        })).unwrap(), None, None, None);
        let template = snapshot.sessions.projections[&id]
            .projection
            .visible_turn_items[0]
            .clone();
        let mut committed = 0;
        let mut decision = "continueReading";
        for (index, page) in self.pages.into_iter().enumerate() {
            let op = ReadHistory {
                session: id.clone(),
            };
            let input = op.capture(&snapshot, "").unwrap();
            assert_eq!(input.1, index.to_string());
            let next_cursor = match page.cursor.as_str() {
                "advance" => Some((index + 1).to_string()),
                "same" => Some(input.1.clone()),
                "missing" => None,
                other => panic!("unexpected Lean cursor: {other}"),
            };
            let items = page
                .rows
                .iter()
                .enumerate()
                .map(|(offset, kind)| {
                    let mut row = template.clone();
                    row.source_item_id = format!("page-{index}-item-{offset}");
                    let item = Arc::make_mut(&mut row.item);
                    item.id = row.source_item_id.clone();
                    // Adjacent work pages can belong to different runs.
                    item.run_id = Some(format!("run-{index}"));
                    item.body = body(kind, &item.id);
                    row
                })
                .collect();
            let response = ThreadHistoryPage {
                snapshot_sequence: 1,
                items,
                nodes: vec![],
                has_more_history: page.more,
                next_cursor: next_cursor.clone(),
            };
            let before = snapshot.clone();
            match op.complete(&mut snapshot, "", (input, response), true) {
                Err(error) => {
                    assert!(error.to_string().contains("history cursor did not advance"));
                    assert_eq!(snapshot, before);
                    decision = "retry";
                    break;
                }
                Ok(effects) => {
                    committed += 1;
                    assert_eq!(
                        snapshot.sessions.projections[&id].history_cursor,
                        next_cursor
                    );
                    if effects.is_empty() {
                        decision = "stop";
                        break;
                    }
                    assert_eq!(effects.len(), 1);
                }
            }
        }
        assert_eq!(
            (committed, decision),
            (self.committed, self.decision.as_str())
        );
    }
}

#[test]
#[ignore = "requires traces generated by HistoryPaging.lean"]
fn lean_core_manual_history_paging() {
    let dir = std::env::var_os("AGENT_CORE_CASES").expect("missing AGENT_CORE_CASES");
    let cases =
        std::fs::read_to_string(std::path::PathBuf::from(dir).join("historypaging.jsonl")).unwrap();
    assert_eq!(cases.lines().count(), 55);
    for line in cases.lines() {
        serde_json::from_str::<Trace>(line).unwrap().check();
    }
}
